const BL = '_______';
const pad2 = (n: number) => String(n).padStart(2, '0');

/** Индекси на думите (по интервал), които съдържат пропуск `___`. */
const blankIdx = (text: string): number[] =>
  text
    .split(' ')
    .map((w, i) => (/_{3,}/.test(w) ? i : -1))
    .filter((i) => i >= 0);

/** workbook_fill_blank ред: пропуски + (по избор) модел `isExample`; верният отговор е първи в `options`. */
function fb(
  text: string,
  correct: string[],
  options: string[][],
  extra: { isExample?: boolean } = {},
): WorkbookFillBlankExercise['sentences'][number] {
  return {
    text,
    blanks: blankIdx(text),
    correctAnswers: correct,
    ...(options.length ? { options } : {}),
    ...(extra.isExample ? { isExample: true } : {}),
  };
}

/** Ред-контекст (без пропуск): показва се като сив ред, не носи точки. */
const ctxLine = (text: string) => fb(text, [], []);

/** Ред-контекст на модела (без пропуск) — отива в карето „Модел:“ (`modelBox`). */
const modelLine = (text: string) => fb(text, [], [], { isExample: true });

/** Dropdown ред с един пропуск: `options[0]` е верният отговор. */
const dd = (text: string, options: string[]) => fb(text, [options[0]], [options]);

