/** Текст за аудио: без `**` / `__`, без „ / “ и „ = “ → пауза. */
const plain = (s: string) =>
  s
    .replace(/\*\*|__/g, '')
    .replace(/ \/ /g, ', ')
    .replace(/ = /g, '. ')
    .replace(/ =$/, '.');

/** Ред в `layout: 'stacked'`: заглавие (`pronoun`, по избор) + редове; `ttsText` се извежда. */
const srow = (pronoun: string, cells: string[]) => ({
  cardStart: true,
  pronoun,
  cells,
  ttsText: [pronoun, ...cells].filter(Boolean).map(plain).join('. ').replace(/\.\./g, '.'),
});

/**
 * Упр. 13: един блок = едно изречение. `{a|b}` = двете форми „X / Y"; префиксът `+` отбелязва
 * верната. Всичко останало (и „/") е неселектируемо. Номерът е първият (неселектируем) токен.
 */
function clickBlock(n: number, marked: string) {
  const re = /\{(\+?)([^|}]+)\|(\+?)([^}]+)\}([.,;:!?…“”"]*)|(\S+)/g;
  const raw: { text: string; selectable: boolean; correct: boolean; trailing: string }[] = [
    { text: `${n}.`, selectable: false, correct: false, trailing: ' ' },
  ];
  let m: RegExpExecArray | null;
  while ((m = re.exec(marked))) {
    if (m[6] !== undefined) {
      raw.push({ text: m[6], selectable: false, correct: false, trailing: ' ' });
    } else {
      raw.push({ text: m[2], selectable: true, correct: m[1] === '+', trailing: ' ' });
      raw.push({ text: '/', selectable: false, correct: false, trailing: ' ' });
      raw.push({ text: m[4], selectable: true, correct: m[3] === '+', trailing: `${m[5] ?? ''} ` });
    }
  }
  return {
    id: `b${n}`,
    tokens: raw.map((t, i): B2SelectableToken => {
      const token: B2SelectableToken = {
        id: `t${pad2(i + 1)}`,
        text: t.text,
        trailing: i === raw.length - 1 ? t.trailing.trimEnd() : t.trailing,
      };
      if (!t.selectable) token.selectable = false;
      if (t.correct) token.correct = true;
      return token;
    }),
  };
}

/** ГРАМАТИКА 5: ред на таблицата; `ttsText` без „(а)" — „казал(а)" → „казал, казала". */
function pastPerfRow(pronoun: string, plus: string, minus: string, q: string) {
  const expand = (s: string) => {
    const t = s.replace(/\*\*/g, '');
    const m = t.match(/^(.*?)казал\(а\)$/);
    return m ? `${m[1]}казал, ${m[1]}казала` : t;
  };
  return {
    pronoun,
    cells: [plus, minus, q],
    ttsText: `${pronoun}. ${[plus, minus, q].map(expand).join('. ')}.`,
  };
}

