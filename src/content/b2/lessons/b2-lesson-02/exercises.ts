/** Аудио-only ред (не се рисува) — вж. `hidden` / `headerAudio` / `lead.audio` / `thenTableAudio` в B2GrammarTableExercise. */
const audioRow = (spoken: string) => ({
  pronoun: '',
  cells: [] as string[],
  hidden: true as const,
  ttsText: spoken,
  ttsModel: 'pro' as const,
  ttsPrompt: ROW_PROMPT,
});

/** Като ROW_PROMPT, но БЕЗ „without long pauses“ — иначе заглушава таговете [short pause]. */
const PAUSE_ROW_PROMPT =
  'Read this Bulgarian text at a natural, brisk conversational pace, clearly, exactly once and in order, without repeating, skipping or replacing any word, with native Bulgarian stress and no foreign accent.';

/** Като audioRow, но с паузи ([short pause]) — за кратки клитики (я, му, им ги), които иначе се губят. */
const pauseAudioRow = (spoken: string) => ({ ...audioRow(spoken), ttsPrompt: PAUSE_ROW_PROMPT });

/** ГРАМАТИКА 4: ред по модела „аз. Нека купя! Нека да купя! Да купя! [пауза] Нека не купувам! …“. */
const complexRow = (pronoun: string, spokenPronoun: string, pos: string, neg: string, boldNeg = false) => ({
  pronoun,
  cells: [`${pos}!`, boldNeg ? `**${neg}!**` : `${neg}!`],
  ttsText:
    `${spokenPronoun}. Нека ${pos}! Нека да ${pos}! Да ${pos}! [short pause] ` +
    `Нека не ${neg}! Нека да не ${neg}! Да не ${neg}!`,
  ttsModel: 'pro' as const,
  ttsPrompt: PAUSE_ROW_PROMPT,
});

/** ГРАМАТИКА 5 (Словоред): „сметката [пауза] я. …“ + трите форми. */
const wordOrderRow = (
  pronoun: string,
  noun: string,
  clitic: string,
  cells: [string, string, string],
) => ({
  pronoun,
  cells,
  ttsText: `${noun}. [short pause] ${clitic}. [short pause] ${cells.map((c) => c.replace(/\*\*/g, '').replace(/ \/ /g, ' или ')).join(' [short pause] ')}`,
  ttsModel: 'pro' as const,
  ttsPrompt: PAUSE_ROW_PROMPT,
});

/** Ред „Соня“ (ГРАМАТИКА 5): и шестте изречения от учебника, всяко четено отделно и пълно. */
const soniaRow = (pronoun: string, noun: string, clitic: string, cells: [string, string, string]) => ({
  ...wordOrderRow(pronoun, noun, clitic, cells),
  ttsText:
    'Поканата на Соня, ѝ я. [short pause] ' +
    'Недей или недейте изпраща поканата на Соня! Недей или недейте ѝ я изпраща! [short pause] ' +
    'Недей да изпращаш поканата на Соня! Недей да ѝ я изпращаш! [short pause] ' +
    'Недейте да изпращате поканата на Соня! Недейте да ѝ я изпращате!',
});
/**
 * УПР. 33 (feedback 2026-10-21, кръг 2): текстът в скобите се чете. Скобите се заменят с пауза:
 * „Обирам каймака (за човек…). Както…“ → „Обирам каймака. [short pause] За човек…. Както…“.
 */
const spokenIdiom = (p: string) =>
  p.replace(/ \(([^)]*)\)\.?/, (_m, g: string) => `. [short pause] ${g.charAt(0).toUpperCase()}${g.slice(1)}.`);

/** Индекси на думите (по интервал), които съдържат пропуск `___`. */
const blankIdx = (text: string): number[] =>
  text
    .split(' ')
    .map((w, i) => (/_{3,}/.test(w) ? i : -1))
    .filter((i) => i >= 0);

/** Преводите на картите идват от гланцовете в content.vocabulary (една истина). */
const glossOf = (word: string) =>
  content.vocabulary?.find((v) => v.bulgarian === word)?.translations;

