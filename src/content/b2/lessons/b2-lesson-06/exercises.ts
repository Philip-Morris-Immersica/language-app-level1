const BL = '_______';

/** Индекси на пропуските (по интервал), както в b2-lesson-03. */
const blankIdx = (text: string): number[] =>
  text
    .split(' ')
    .map((w, i) => (/_{3,}/.test(w) ? i : -1))
    .filter((i) => i >= 0);

/** workbook_fill_blank ред: един пропуск, собствен набор от опции; `isExample` = модел без точки. */
function fb(
  text: string,
  correct: string[],
  options: string[][],
  extra: { isExample?: boolean } = {},
): WorkbookFillBlankExercise['sentences'][number] {
  return {
    text,
    blanks: blankIdx(text),
    correctAnswers: correct,
    options,
    ...(extra.isExample ? { isExample: true } : {}),
  };
}

/** Номерира реалните редове 1..N (моделът остава без номер); blanks се преизчисляват. */
function numberRows(rows: WorkbookFillBlankExercise['sentences']) {
  let n = 0;
  return rows.map((s) => {
    if (s.isExample) return s;
    const text = `${++n}. ${s.text}`;
    return { ...s, text, blanks: blankIdx(text) };
  });
}

