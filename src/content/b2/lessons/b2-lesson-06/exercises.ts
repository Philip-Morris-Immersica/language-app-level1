type NegRow = [string, string, string, string[]];
function negationEx(n: number, order: number, textbookNo: number, model: NegRow, rows: NegRow[]): WorkbookFillBlankExercise {
  const row = ([source, neg, answer, wrong]: NegRow, i: number, extra: { isExample?: boolean } = {}) => {
    const options = [...wrong];
    options.splice((i * 3 + 1) % 4, 0, answer);
    return fb(`${source} → ${neg} ${BL}.`, [answer], [options], extra);
  };
  return {
    id: `b2-l06-ex-${pad2(n)}`,
    type: 'workbook_fill_blank',
    title: `УПРАЖНЕНИЕ ${textbookNo}`,
    instruction: 'Изберете правилната отрицателна форма по модела.',
    instructionKey: 'b2.l06.ex26',
    order,
    points: rows.length,
    layout: 'single',
    hideSentenceNumbers: true,
    modelBox: true,
    sentences: numberRows([row(model, 0, { isExample: true }), ...rows.map((r, i) => row(r, i))]),
  } as WorkbookFillBlankExercise;
}

