/** Разбърква пула детерминирано (стъпка, взаимно проста с дължината) — различно от реда на двойките. */
function scrambled(pairs: Pair[], step: number): string[] {
  const rights = pairs.map(([, r]) => r);
  const n = rights.length;
  return rights.map((_, i) => rights[(i * step + 1) % n]);
}

