/** ГРАМАТИКА 1–2: ред на таблицата; `ttsText` без `**`, „той / тя / то“ → „той, тя, то“. */
function tenseRow(pronoun: string, cells: string[], ttsModel?: 'pro' | 'flash') {
  const plain = (s: string) => s.replace(/\*\*/g, '');
  return {
    pronoun,
    cells,
    ttsText: `${plain(pronoun).replace(/ \/ /g, ', ')}. ${cells.map(plain).join('. ')}.`,
  };
}

/** ГРАМАТИКА 3: каре на наставка — заглавие (`pronoun`) + примери (една зелена линия). */
function suffixCard(pronoun: string, examples: string, spokenPronoun: string, spokenExamples?: string) {
  return {
    cardStart: true,
    pronoun,
    cells: [examples],
    ttsText: `${spokenPronoun}. ${(spokenExamples ?? examples).charAt(0).toUpperCase()}${(spokenExamples ?? examples).slice(1)}.`,
  };
}

