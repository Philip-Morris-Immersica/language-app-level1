function futureRows(negative: boolean) {
  const prefixOf = (reflexive: boolean) =>
    negative ? (reflexive ? 'няма да се' : 'няма да') : reflexive ? 'ще се' : 'ще';
  const example = negative
    ? fb(`Той ${BL} сметката. (платя)`, ['няма да плати'], [['няма да платя', 'няма да платиш', 'няма да плати', 'няма да платим', 'няма да платят']], { isExample: true })
    : fb(`Той ${BL} сметката. (платя)`, ['ще плати'], [['ще платя', 'ще платиш', 'ще плати', 'ще платим', 'ще платят']], { isExample: true });
  return numberRows([
    example,
    ...FUTURE_ROWS.map(([sentence, verb, reflexive, forms, ci], i) => {
      const prefix = prefixOf(reflexive);
      // Въпросително изречение (без „нали“): „ли“ след глагола; в отрицание — „няма ли да“.
      const isQuestion = sentence.trimEnd().endsWith('?') && !sentence.includes('нали');
      const fmt = (form: string) =>
        !isQuestion
          ? `${prefix} ${form}`
          : negative
            ? `${prefix.replace('няма да', 'няма ли да')} ${form}`
            : `${prefix} ${form} ли`;
      return fb(
        `${sentence.replace('___', BL)} (${verb})`,
        [fmt(forms[ci])],
        [futureOptions(fmt, forms, ci, i)],
      );
    }),
  ]);
}

// Упр. 23 — шаблон с „___“: един и същ текст за двете версии („щях… / нямаше…“).
// Опциите са с главна буква само когато бланката е първа дума в изречението.
const PLUS = ['щях', 'щеше', 'щяхме', 'щяхте', 'щяха'];
const MINUS = ['нямаше', 'нямахме', 'няма', 'нямаха', 'нямало'];
const capFirst = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);

/**
 * Един ред на упр. 23. `tpl` = изречението с „___“; `plus` = вярната форма(и) за (+) в реда на бланките
 * (с правилния регистър). (–) е винаги „нямаше“ (с главна буква при начална бланка).
 */
function tenseRowEx(tpl: string, plus: string[]) {
  const [prompt, answerPart] = tpl.split(' → ');
  const marked = answerPart.replace(/___/g, BL);
  const minus = plus.map((p) => (p === capFirst(p) ? 'Нямаше' : 'нямаше'));
  const setFor = (answer: string, base: string[]) =>
    answer === capFirst(answer) ? base.map(capFirst) : [...base];
  return fb(`${prompt} → ${marked} / ${marked}`, [...plus, ...minus], [
    ...plus.map((p) => setFor(p, PLUS)),
    ...minus.map((m) => setFor(m, MINUS)),
  ]);
}

