/**
 * Упр. 21/22: 5 опции на ред = вярната форма + 4 от другите лица на същия глагол.
 * `forms` = [аз, ти, той, ние, Вие, те]; `prefix` = „ще“ / „ще се“ / „няма да“ / „няма да се“.
 * Пропуснатият дистрактор и позицията на верния се въртят по номера на реда (компонентът така или иначе разбърква).
 */
function futureOptions(fmt: (form: string) => string, forms: string[], correctIdx: number, row: number): string[] {
  const others = forms.filter((_, i) => i !== correctIdx).map(fmt);
  others.splice(row % others.length, 1);
  others.splice((row * 2 + 1) % 5, 0, fmt(forms[correctIdx]));
  return others;
}

