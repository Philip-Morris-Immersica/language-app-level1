/**
 * 8 блока (¶1–¶8) от текста на мечките. `targets` = { blockId: [думи] } — за всяка дума се
 * маркира като верен ПЪРВИЯТ още немаркиран token с точно този текст в блока.
 * Хвърля при грешка в ключа, за да не остане дума немаркирана.
 */
function bearBlocks(targets: Record<string, string[]> = {}) {
  return BEAR_PARAGRAPHS.map((text, i) => {
    const id = `p${i + 1}`;
    const tokens = buildTokens(text);
    for (const word of targets[id] ?? []) {
      const tok = tokens.find((t) => t.text === word && !t.correct);
      if (!tok) throw new Error(`b2-l01: думата „${word}“ не е намерена в блок ${id} (текст мечки)`);
      tok.correct = true;
    }
    return { id, tokens };
  });
}

