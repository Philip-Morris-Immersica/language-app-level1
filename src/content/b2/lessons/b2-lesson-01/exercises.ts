const pad2 = (n: number) => String(n).padStart(2, '0');

/** Индекси на думите (по интервал), които съдържат пропуск `___`. */
const blankIdx = (text: string): number[] =>
  text
    .split(' ')
    .map((w, i) => (/_{3,}/.test(w) ? i : -1))
    .filter((i) => i >= 0);

/** workbook_fill_blank ред с един пропуск. */
function fb(
  text: string,
  correct: string,
  options: string[],
  extra: { acceptable?: string[]; isExample?: boolean } = {},
): WorkbookFillBlankExercise['sentences'][number] {
  return {
    text,
    blanks: blankIdx(text),
    correctAnswers: [correct],
    ...(extra.acceptable ? { acceptableAnswers: [extra.acceptable] } : {}),
    options,
    ...(extra.isExample ? { isExample: true } : {}),
  };
}

/** Преводите на картите идват от гланцовете в content.vocabulary (една истина). */
const glossOf = (word: string) =>
  content.vocabulary?.find((v) => v.bulgarian === word)?.translations;

function wordCards(exId: string, words: string[]): IllustratedCardsExercise['cards'] {
  return words.map((label, i) => ({
    id: `${exId}-${pad2(i + 1)}`,
    imageUrl: '',
    label,
    translations: glossOf(label),
  }));
}

/**
 * Токенизира текст за `b2-select-words-inline`.
 * `{...}` = верен token (може да е с интервали: {Стара планина}); пунктуацията отива в `trailing`;
 * самостоятелно „–" е неселектируем token.
 */
function buildTokens(marked: string): B2SelectableToken[] {
  const re = /\{([^}]+)\}([.,;:!?…)”"]*)|(\S+)/g;
  const raw: { text: string; punct: string; correct: boolean; selectable: boolean }[] = [];
  let m: RegExpExecArray | null;
  while ((m = re.exec(marked))) {
    if (m[1] !== undefined) {
      raw.push({ text: m[1], punct: m[2] ?? '', correct: true, selectable: true });
    } else {
      const word = m[3];
      if (word === '–') {
        raw.push({ text: word, punct: '', correct: false, selectable: false });
      } else {
        const parts = word.match(/^(.+?)([.,;:!?…)”"]*)$/)!;
        raw.push({ text: parts[1], punct: parts[2], correct: false, selectable: true });
      }
    }
  }
  return raw.map((t, i) => {
    const last = i === raw.length - 1;
    const token: B2SelectableToken = {
      id: `t${pad2(i + 1)}`,
      text: t.text,
      trailing: t.punct + (last ? '' : ' '),
    };
    if (!t.selectable) token.selectable = false;
    if (t.correct) token.correct = true;
    return token;
  });
}

