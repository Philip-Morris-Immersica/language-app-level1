/**
 * Токенизира текст за `b2-select-words-inline`.
 * `{...}` = верен token (може да е с интервали: {Стара планина}); пунктуацията отива в `trailing`;
 * самостоятелно „–" е неселектируем token.
 */
function buildTokens(marked: string): B2SelectableToken[] {
  const re = /\{([^}]+)\}([.,;:!?…)”"]*)|(\S+)/g;
  const raw: { text: string; punct: string; correct: boolean; selectable: boolean }[] = [];
  let m: RegExpExecArray | null;
  while ((m = re.exec(marked))) {
    if (m[1] !== undefined) {
      raw.push({ text: m[1], punct: m[2] ?? '', correct: true, selectable: true });
    } else {
      const word = m[3];
      if (word === '–') {
        raw.push({ text: word, punct: '', correct: false, selectable: false });
      } else {
        const parts = word.match(/^(.+?)([.,;:!?…)”"]*)$/)!;
        raw.push({ text: parts[1], punct: parts[2], correct: false, selectable: true });
      }
    }
  }
  return raw.map((t, i) => {
    const last = i === raw.length - 1;
    const token: B2SelectableToken = {
      id: `t${pad2(i + 1)}`,
      text: t.text,
      trailing: t.punct + (last ? '' : ' '),
    };
    if (!t.selectable) token.selectable = false;
    if (t.correct) token.correct = true;
    return token;
  });
}

