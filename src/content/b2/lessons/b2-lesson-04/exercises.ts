/** Текст за аудио: без `**`, без „ / “ и „ – “, „ = “ → пауза. */
const plain = (s: string) =>
  s
    .replace(/\*\*/g, '')
    .replace(/__/g, '')
    .replace(/ \/ /g, ', ')
    .replace(/ – /g, ', ')
    .replace(/ = /g, '. ')
    .replace(/ =$/, '.');

/** Ред в `layout: 'stacked'`: заглавие (`pronoun`, по избор) + редове; `ttsText` се извежда, ако не е зададен. */
const srow = (pronoun: string, cells: string[], ttsText?: string, cardStart = true) => ({
  cardStart,
  pronoun,
  cells,
  ttsText: ttsText ?? [pronoun, ...cells].filter(Boolean).map(plain).join('. ').replace(/\.\./g, '.'),
});

/** Номерира реалните редове 1..N (моделът остава без номер); blanks се преизчисляват. */
function numberRows(rows: WorkbookFillBlankExercise['sentences']) {
  let n = 0;
  return rows.map((s) => {
    if (s.isExample) return s;
    const text = `${++n}. ${s.text}`;
    return { ...s, text, blanks: blankIdx(text) };
  });
}

