/**
 * Токенизира текст за `b2-select-words-inline`: `{фраза}` = верен token (фразов, 1 т.); пунктуацията
 * след думата отива в `trailing`; отварящата кавичка „ („ преди дума) се слива с `trailing` на предходния token.
 */
function buildTokens(marked: string, prefix: string, bullet = false): B2SelectableToken[] {
  const re = /([„(]*)(?:\{([^}]+)\}|([^\s{}„]+?))([.,;:!?…“”"”)]*)(?:\s+|$)/g;
  const raw: { lead: string; text: string; punct: string; correct: boolean }[] = [];
  let m: RegExpExecArray | null;
  while ((m = re.exec(marked))) {
    raw.push({ lead: m[1] ?? '', text: m[2] ?? m[3], punct: m[4] ?? '', correct: m[2] !== undefined });
  }
  const tokens: B2SelectableToken[] = raw.map((t, i) => {
    const next = raw[i + 1];
    const token: B2SelectableToken = {
      id: `${prefix}t${String(i + 1).padStart(2, '0')}`,
      text: (i === 0 ? t.lead : '') + t.text,
      trailing: t.punct + (next ? (next.lead ? ` ${next.lead}` : ' ') : ''),
    };
    if (t.correct) token.correct = true;
    return token;
  });
  if (bullet) tokens.unshift({ id: `${prefix}bullet`, text: '•', trailing: ' ', selectable: false });
  return tokens;
}

