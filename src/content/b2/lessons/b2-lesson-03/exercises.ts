/** Индекси на думите (по интервал), които съдържат пропуск `___`. */
const blankIdx = (text: string): number[] =>
  text
    .split(' ')
    .map((w, i) => (/_{3,}/.test(w) ? i : -1))
    .filter((i) => i >= 0);

/** workbook_fill_blank ред: един или повече пропуски, `options` е по един масив на пропуск. */
function fb(
  text: string,
  correct: string[],
  options: string[][],
): WorkbookFillBlankExercise['sentences'][number] {
  return { text, blanks: blankIdx(text), correctAnswers: correct, options };
}

