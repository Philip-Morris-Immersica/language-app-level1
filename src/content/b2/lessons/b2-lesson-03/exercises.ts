/** workbook_fill_blank ред с пример и/или допълнителни приети отговори (по blank). */
function fbx(
  text: string,
  correct: string[],
  options: string[][],
  extra: { isExample?: boolean; acceptable?: string[][] } = {},
): WorkbookFillBlankExercise['sentences'][number] {
  return {
    ...fb(text, correct, options),
    ...(extra.isExample ? { isExample: true } : {}),
    ...(extra.acceptable ? { acceptableAnswers: extra.acceptable } : {}),
  };
}

/** Номерира реалните редове 1..N (моделът остава без номер); blanks се преизчисляват. */
function numberRows(rows: WorkbookFillBlankExercise['sentences']) {
  let n = 0;
  return rows.map((s) => {
    if (s.isExample) return s;
    const text = `${++n}. ${s.text}`;
    return { ...s, text, blanks: blankIdx(text) };
  });
}

const pad2 = (n: number) => String(n).padStart(2, '0');

/**
 * Токенизира текст за `b2-select-words-inline`: `{дума}` = верен token; пунктуацията отива в
 * `trailing`; „Рени:“ / „Валя:“ са неселектируеми.
 */
function buildTokens(marked: string): B2SelectableToken[] {
  const re = /\{([^}]+)\}([.,;:!?…)”"]*)|(\S+)/g;
  const raw: { text: string; punct: string; correct: boolean; selectable: boolean }[] = [];
  let m: RegExpExecArray | null;
  while ((m = re.exec(marked))) {
    if (m[1] !== undefined) {
      raw.push({ text: m[1], punct: m[2] ?? '', correct: true, selectable: true });
    } else if (m[3] === 'Рени:' || m[3] === 'Валя:') {
      raw.push({ text: m[3], punct: '', correct: false, selectable: false });
    } else {
      const parts = m[3].match(/^(.+?)([.,;:!?…)”"]*)$/)!;
      raw.push({ text: parts[1], punct: parts[2], correct: false, selectable: true });
    }
  }
  return raw.map((t, i) => {
    const token: B2SelectableToken = {
      id: `t${pad2(i + 1)}`,
      text: t.text,
      trailing: t.punct + (i === raw.length - 1 ? '' : ' '),
    };
    if (!t.selectable) token.selectable = false;
    if (t.correct) token.correct = true;
    return token;
  });
}

