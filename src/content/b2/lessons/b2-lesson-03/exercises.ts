/** Упр. 16 — един блок = едно изречение; опциите от SC с малка буква, `ok` = верни (Q3-А: „под“ в №2). */
function prepBlock(n: number, sentence: string, options: [string, boolean][]) {
  return {
    id: `b${n}`,
    heading: `${n}. ${sentence}`,
    tokens: options.map(([text, ok], i): B2SelectableToken => ({
      id: `t${pad2(i + 1)}`,
      text,
      trailing: i === options.length - 1 ? '' : ' ',
      ...(ok ? { correct: true } : {}),
    })),
  };
}

